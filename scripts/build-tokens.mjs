import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(resolve(root, 'src/tokens/tokens.json'), 'utf8'));

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const lines = [];
const add = (name, value) => lines.push(`  --ds-${name}: ${value};`);

add('font-family', tokens.fontFamily.stack);
add('font-mono', tokens.fontFamily.mono);

for (const [family, { steps }] of Object.entries(tokens.colors)) {
  for (const [step, hex] of Object.entries(steps)) add(`color-${family}-${step}`, hex);
}
for (const [name, px] of Object.entries(tokens.spacing.steps)) add(`space-${name}`, `${px}px`);
for (const [name, px] of Object.entries(tokens.radius)) add(`radius-${name}`, `${px}px`);
for (const s of tokens.shadows.styles) add(slug(s.name), s.css);
for (const t of tokens.typography.styles) {
  const key = slug(t.name);
  add(`${key}-size`, `${t.size}px`);
  if (t.lineHeight) add(`${key}-line-height`, `${t.lineHeight}px`);
}

const css = `/* GENERATED by scripts/build-tokens.mjs from src/tokens/tokens.json. Do not edit. */\n:root {\n${lines.join('\n')}\n}\n`;
writeFileSync(resolve(root, 'src/tokens/tokens.css'), css);
console.log(`tokens.css written (${lines.length} custom properties)`);

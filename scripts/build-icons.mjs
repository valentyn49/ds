import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const directory = new URL('../src/components/icons/', import.meta.url);
const manifestURL = new URL('figma-manifest.json', directory);
const manifest = JSON.parse(readFileSync(manifestURL, 'utf8'));
const names = new Set();
const nodes = new Set();
const records = manifest.entries.map((entry, index) => {
  if (names.has(entry.name) || nodes.has(entry.nodeId)) throw new Error(`Duplicate icon: ${entry.name}`);
  names.add(entry.name); nodes.add(entry.nodeId);
  const svg = readFileSync(new URL(`assets/${entry.asset}`, directory), 'utf8');
  const hash = createHash('sha256').update(svg).digest('hex');
  if (process.argv.includes('--record-hashes')) entry.sourceSha256 = hash;
  if (entry.sourceSha256 !== hash) throw new Error(`SVG changed since Figma export: ${entry.asset}`);
  if (!svg.startsWith('<svg ') || !svg.includes('</svg>')) throw new Error(`Invalid SVG: ${entry.asset}`);
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  if (viewBox !== entry.viewBox) throw new Error(`Viewport mismatch: ${entry.asset}`);
  const { name, figmaName, nodeId, nodeType, category, width, height, variants, rendering, colorCustomizable, defaultColor, asset } = entry;
  return { index, metadata: { name, figmaName, nodeId, nodeType, category, width, height, viewBox, variants, rendering, colorCustomizable, defaultColor, asset } };
});
if (process.argv.includes('--record-hashes')) writeFileSync(manifestURL, JSON.stringify(manifest, null, 2) + '\n');
const imports = records.map(({ index, metadata }) => `import svg${index} from './assets/${metadata.asset}?raw';`).join('\n');
const entries = records.map(({ index, metadata }) => `  ${JSON.stringify(metadata.name)}: { ${JSON.stringify(metadata).slice(1, -1)}, svg: svg${index} },`).join('\n');
const output = `// Generated by scripts/build-icons.mjs from figma-manifest.json and original SVG assets.\n${imports}\n\nexport const ICON_REGISTRY = {\n${entries}\n} as const;\n\nexport type FigmaIconName = keyof typeof ICON_REGISTRY;\nexport const FIGMA_ICON_NAMES = Object.keys(ICON_REGISTRY) as FigmaIconName[];\nexport const ICON_ENTRIES = Object.values(ICON_REGISTRY);\nexport type IconEntry = (typeof ICON_ENTRIES)[number];\n`;
writeFileSync(new URL('icon-registry.ts', directory), output);
console.log(`${records.length} verified Figma SVG assets → ${fileURLToPath(new URL('icon-registry.ts', directory))}`);
